export const PATTERNS = {
  /* ---------- 日期 ---------- */
  // 2026年9月18日 / 2026-09-18 / 2026/9/18 / 2026.9.18
  FULL_DATE: /(\d{4})\s*[年\-\/.]\s*(\d{1,2})\s*[月\-\/.]\s*(\d{1,2})\s*日?/,
  // 9月18日 / 9月18号
  CN_MONTH_DAY: /(\d{1,2})\s*月\s*(\d{1,2})\s*[日号]/,
  // 9.18 / 9-18 / 9/18 （需避免误伤 14:30 之类，靠后处理约束）
  SHORT_MONTH_DAY: /(?<!\d)(\d{1,2})\s*[.\-\/]\s*(\d{1,2})(?!\d)(?!\s*[:：])/,
  // 9月18日（中文数字） 九月十八日 / 九月十八号
  // 日期部分限定为中文数字，避免贪婪吞掉后面「下午三点」的「三」
  CN_NUM_MONTH_DAY: /([一二三四五六七八九十]{1,2})\s*月\s*([一二三四五六七八九十]{1,3})(?=\s*[日号])/,

  /**
   * 用户手输的「整串就是一个日期」——校验用，**必须锚定首尾**。
   *
   * ⚠️ 和上面的 FULL_DATE 是两件事，别合并：
   *    FULL_DATE 是「在一整段通知文字里把日期捞出来」，不锚定是它的本分；
   *    这一条是「用户填的这个输入框，整体是不是一个合法日期」，
   *    不锚定的话「2026-10-08 随便写点什么」也会被判成合法。
   *
   * 用户 2026-09-22 明确要求：不要只认 2026-10-08 一种写法。
   * 放行的分隔符：- / . 年 月 日（可混用，如 2026.3.8、2026/3/8、2026年3月8日）
   */
  DATE_INPUT: /^(\d{4})\s*[年\-\/.]\s*(\d{1,2})\s*[月\-\/.]\s*(\d{1,2})\s*[日号]?$/,

  /* ---------- 时间 ---------- */
  // 14:30 / 14：30 / 14:30:00
  COLON_TIME: /(\d{1,2})\s*[:：]\s*(\d{2})(?:\s*[:：]\s*(\d{2}))?/,
  // 15时 / 15点 / 15时30分 / 3点半 / 15点整
  CN_HOUR: /(\d{1,2}|[一二三四五六七八九十]{1,3})\s*[点时](?:\s*(\d{1,2}|[一二三四五六七八九十]{1,3})\s*分?)?/,
  // 上午 / 下午 / 晚上 / 中午 / 傍晚 / 凌晨 / 早上 / 今晚 / 明晚
  DAY_PERIOD: /(上午|下午|中午|晚上|傍晚|凌晨|早上|晚间|今晚|明晚|昨晚)/,
  HALF: /半/,
  QUARTER: /(一刻|三刻|(\d{1,2})分)/,

  /* ---------- 地点 ---------- */
  // 地点：xxx  （行内到行尾）
  LOCATION_INLINE: /(?:活动地点|报告地点|会议地点|讲座地点|举办地点|开会地点|地\s*点|地址|会场)\s*[:：]\s*(.+)/,
  // 本次会议在社科楼A101举行 / 在xx楼xx室举行 / 于xx报告厅举办
  // 关键约束：地点前半段不得包含「月/日/号/点/时/分/午/晚/早」等时间字，
  // 否则「于9月20日…在社科楼报告厅」会被整体吞掉
  LOCATION_IN_SENTENCE: /(?:在|于)\s*([^，。；、\s:：月日号点时分午晚早晨]{0,26}?(?:楼|室|厅|馆|学院|中心|校区|教室|会议室|报告厅|礼堂)(?:[A-Za-z0-9\-（）()]{0,10})?)\s*(?:举行|举办|召开|进行|开展|签到)/,
  // 独立地点行：数学学院201报告厅 / 信息楼A201
  LOCATION_LINE: /^[\u4e00-\u9fa5A-Za-z0-9\-（）()]{2,40}?(?:楼|室|厅|馆|学院|中心|校区|教室|会议室|报告厅|礼堂)[\u4e00-\u9fa5A-Za-z0-9\-（）()]{0,20}$/,

  /* ---------- 标题 ---------- */
  // 报告题目：xxx  （含「宣讲单位」「单位名称」这类等价的名称型字段）
  TITLE_INLINE: /(?:^|[^\u4e00-\u9fa5])(?:报告题目|讲座题目|学术报告题目|活动名称|讲座名称|报告名称|会议名称|宣讲单位|宣讲名称|单位名称|活动主题|讲座主题|报告主题|会议主题|主\s*题|题\s*目|活\s*动|讲\s*座|报\s*告|会\s*议|宣\s*讲|培\s*训|沙\s*龙|论\s*坛|内\s*容)\s*[:：]\s*(.+)/,
  /**
   * 「主题为：xxx」/「主题是 xxx」这类叙述式题目引入。
   * 通知里极常见的写法：「…在博学楼B412会议室举行讲座，主题为：考虑交易成本的最优…」
   * 优先级要高于句子内嵌的「举行/进行」兜底 —— 那个「进行」往往指的是
   * 「在群内进行签到」这类与活动名无关的动作，会把签到当成活动名。
   */
  TITLE_TOPIC_IN_SENTENCE: /(?:主题|题目)\s*(?:为|是|：|:)\s*[：:，,、]?\s*([^，。；;！!？?（）()\s]{2,80})/,
  // 「主题为：xxx」的完整句子形式：要求出现在「小句边界之后」，
  // 用它避免把「活动名称：xxx」「讲座主题：xxx」这类字段标签行误判成叙述句。
  TITLE_TOPIC_FULL_SENTENCE: /(?:[，,；;。！!？?、]\s*)(?:主题|题目)\s*(?:为|是|：|:)\s*[：:，,、]?\s*([^，。；;！!？?（）()\s]{2,80})/,
  // 书名号 / 引号包裹的题目
  TITLE_QUOTED: /[《“"]([^》”"]{4,60})[》”"]/,
  /**
   * 句子内嵌的活动名：「…举行研究生就业宣讲会」。
   * 关键约束（v1.3.0 修）：
   *   1) 动词要带界限，避免「我们将在群内进行活动签到」这种把「进行」当引入词；
   *   2) 结果里必须含活动类型词，否则「活动签到」「相关工作」都会被捞出来。
   */
  TITLE_IN_SENTENCE: /(?:举行|举办|召开|开展)\s*(?:了\s*)?(?:一场|一次|一场题为|题为)?\s*([^，。；、\s]{3,40}?)(?=[，。,.]|$)/,
  // 报告人 / 主讲人 / 主持人
  SPEAKER_LINE: /(?:主讲人|报告人|主持人|主讲|报告者|分享人|嘉宾)\s*[:：]?\s*(.+)/,

  /* ---------- 报告人（学术类专用） ---------- */
  // 行内字段：报告人：张伟教授 / 主讲人: 李敏 / 特邀报告人：王某某
  SPEAKER_INLINE: /(?:特邀报告人|主旨报告人|报告人|主讲人|演讲人|汇报人|分享人|报告者|主讲嘉宾|特邀嘉宾)\s*[:：]\s*(.+)/,
  // 跨行标签行：「报告人：」单独一行
  SPEAKER_LABEL_ONLY: /^(?:特邀报告人|主旨报告人|报告人|主讲人|演讲人|汇报人|分享人|报告者|主讲嘉宾|特邀嘉宾)\s*[:：]?$/,
  // 句子内：「由张伟教授主讲」「张伟教授作报告」「特邀李敏博士主讲」
  // v1.3.0 修：原来只认 2~4 个汉字，导致「邀请到… Harry Zhang 教授于…举行讲座」
  // 这类**英文姓名**完全提取不到。现在允许多词英文姓名（2~4 个词），
  // 并允许中间夹「来自 XX 的」这类单位插入语。
  SPEAKER_IN_SENTENCE: /(?:由|特邀|邀请|邀请到|请到|聘请)\s*(?:来自[^，。]{2,20}?的\s*)?(?:[\u4e00-\u9fa5]{2,12}(?:大学|学院|研究院|研究所|实验室|中心|医院|公司|集团|银行|部|系|所)\s*)?([\u4e00-\u9fa5]{2,4}|[A-Za-z][A-Za-z.\-']*(?:\s+[A-Za-z][A-Za-z.\-']*){1,3})\s*(?:教授|副教授|研究员|博士|院士|老师|讲师|先生|女士)?\s*(?:主讲|作报告|做报告|报告|分享|演讲|举行)/,
  // 「Harry Zhang 教授于9月28日…举行讲座」——英文姓名+职称直接出现在句子里，
  // 前面没有「由/邀请」引入词时的兜底
  SPEAKER_NAME_TITLE_INLINE: /([\u4e00-\u9fa5]{2,4}|[A-Za-z][A-Za-z.\-']*(?:\s+[A-Za-z][A-Za-z.\-']*){1,3})\s*(?:教授|副教授|研究员|副研究员|博士|院士|讲师)\s*(?:将于|于|将在|在|将)/,
  // 「报告人：张三（清华大学）」
  SPEAKER_WITH_AFFILIATION: /([\u4e00-\u9fa5]{2,4})\s*[（(]([^）)]{2,30})[）)]/,

  /* ---------- 噪声行（不应作为标题） ---------- */
  NOISE_LINE: /^(?:时间|地点|报告人|主讲人|主持人|主办|承办|协办|联系|联系人|电话|邮箱|备注|注意|欢迎|诚邀|届时|请|温馨提示|主办单位|承办单位)\s*[:：]?/,

  /* ---------- 显示格式化（不是解析规则，但同样不写死在页面里） ---------- */
  // 金额千分位：¥10620.00 → ¥10,620.00
  // ⚠️ 带 g 标志的正则**只能**用于 String.replace。拿去 .test() / .exec()
  //    会因 lastIndex 残留而时对时错（第一次 true、第二次 false）。
  MONEY_GROUP: /\B(?=(\d{3})+(?!\d))/g,

  /* ---------- 其他 ---------- */
  // 「本周五」「下周三」「周五」等相对日期
  WEEKDAY_REF: /(本|这|下|次)?\s*(?:周|星期|礼拜)\s*([一二三四五六日天1-7])/,
  // 「今天」「明天」「后天」「今晚」「明晚」
  RELATIVE_DAY: /(大后天|后天|明天|明日|今晚|明晚|今早|今晨|今天|今日)/,
};
